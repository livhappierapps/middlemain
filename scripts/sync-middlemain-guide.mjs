import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const source = new URL('../docs/middlemain-user-guide.md', import.meta.url);
const target = new URL('../artifacts/middlemain/constants/appGuide.ts', import.meta.url);
const sections = readFileSync(source, 'utf8').split(/^## /m).slice(1).map((section) => {
  const newline = section.indexOf('\n');
  return { title: section.slice(0, newline).trim(), content: section.slice(newline + 1).trim() };
});
if (sections.length < 10 || sections.some((section) => !section.title || !section.content)) {
  throw new Error('Guide must include complete, titled feature sections');
}
const generated = '// Generated by scripts/sync-middlemain-guide.mjs. Edit docs/middlemain-user-guide.md instead.\n' +
  `export const APP_GUIDE_SECTIONS = ${JSON.stringify(sections, null, 2)};\n`;
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== generated) throw new Error('Bundled guide is stale: run pnpm run guide:sync');
  console.log(`Guide matches its ${sections.length} canonical sections.`);
} else {
  writeFileSync(target, generated);
  console.log(`Bundled ${sections.length} guide sections in ${fileURLToPath(target)}.`);
}
